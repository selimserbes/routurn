package result

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const (
	publicResultsDir         = "results"
	publicResultsFallbackDir = "routurn-results"
	managedMarkerName        = ".routurn-managed"
	managedMarkerContents    = "routurn-managed-results-v1\nFiles in this directory are generated by Routurn and may be replaced automatically.\n"
)

type Metadata struct {
	Task       string   `json:"task"`
	RunID      string   `json:"run_id"`
	UpdatedAt  string   `json:"updated_at"`
	Files      []string `json:"files,omitempty"`
	PublicPath string   `json:"public_path,omitempty"`
}

func Dir(root, task string) string {
	return filepath.Join(root, ".routurn", "results", taskDirName(task))
}

// IsManagedPublicRoot reports whether path is a Routurn-owned public result root.
// It is intentionally strict so a user's unrelated results/ directory is never
// excluded from sync or modified by Routurn merely because of its name.
func IsManagedPublicRoot(path string) bool {
	data, err := os.ReadFile(filepath.Join(path, managedMarkerName))
	return err == nil && string(data) == managedMarkerContents
}

func Materialize(root, task, runID, sourceDir string) (string, []string, error) {
	if sourceDir == "" {
		return "", nil, fmt.Errorf("empty result source")
	}
	root, err := filepath.Abs(root)
	if err != nil {
		return "", nil, err
	}
	dest := Dir(root, task)
	parent := filepath.Dir(dest)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return "", nil, err
	}
	tmp, err := os.MkdirTemp(parent, ".result-*")
	if err != nil {
		return "", nil, err
	}
	defer os.RemoveAll(tmp)

	files, err := copyTree(sourceDir, tmp)
	if err != nil {
		return "", nil, err
	}

	old := dest + ".old"
	_ = os.RemoveAll(old)
	if _, err := os.Stat(dest); err == nil {
		if err := os.Rename(dest, old); err != nil {
			return "", nil, err
		}
	}
	if err := os.Rename(tmp, dest); err != nil {
		if _, statErr := os.Stat(old); statErr == nil {
			_ = os.Rename(old, dest)
		}
		return "", nil, err
	}

	publicPath, publishErr := publishPublic(root, task, dest, files)
	if publishErr != nil {
		_ = os.RemoveAll(dest)
		if _, statErr := os.Stat(old); statErr == nil {
			_ = os.Rename(old, dest)
		}
		return "", nil, publishErr
	}

	meta := Metadata{
		Task:       task,
		RunID:      runID,
		UpdatedAt:  time.Now().UTC().Format(time.RFC3339),
		Files:      files,
		PublicPath: relativePublicPath(root, publicPath),
	}
	if err := writeMetadata(filepath.Join(dest, "result.json"), meta); err != nil {
		return "", nil, err
	}
	_ = os.RemoveAll(old)
	return publicPath, files, nil
}

func Read(root, task string) (Metadata, string, error) {
	root, err := filepath.Abs(root)
	if err != nil {
		return Metadata{}, "", err
	}
	dir := Dir(root, task)
	data, err := os.ReadFile(filepath.Join(dir, "result.json"))
	if err != nil {
		return Metadata{}, "", err
	}
	var meta Metadata
	if err := json.Unmarshal(data, &meta); err != nil {
		return Metadata{}, "", err
	}

	if meta.PublicPath != "" {
		publicPath := meta.PublicPath
		if !filepath.IsAbs(publicPath) {
			publicPath = filepath.Join(root, filepath.FromSlash(publicPath))
		}
		if _, err := os.Stat(publicPath); err == nil {
			return meta, publicPath, nil
		}
	}

	// Results created by older Routurn versions are upgraded lazily. This makes
	// the visible stable result available without forcing the task to run again.
	publicPath, err := publishPublic(root, task, dir, meta.Files)
	if err != nil {
		return Metadata{}, "", err
	}
	meta.PublicPath = relativePublicPath(root, publicPath)
	if err := writeMetadata(filepath.Join(dir, "result.json"), meta); err != nil {
		return Metadata{}, "", err
	}
	return meta, publicPath, nil
}

func publishPublic(root, task, sourceDir string, files []string) (string, error) {
	if len(files) == 0 {
		return "", fmt.Errorf("result contains no artifact files")
	}
	publicRoot, err := ensurePublicRoot(root)
	if err != nil {
		return "", err
	}
	if err := ensureGitLocalExclude(root, filepath.Base(publicRoot)); err != nil {
		return "", err
	}

	taskDest := filepath.Join(publicRoot, taskDirName(task))
	tmp, err := os.MkdirTemp(publicRoot, ".task-*")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmp)

	publicPath := taskDest
	if len(files) == 1 {
		source := filepath.Join(sourceDir, filepath.FromSlash(files[0]))
		name := "latest" + stableSuffix(filepath.Base(files[0]))
		target := filepath.Join(tmp, name)
		if err := linkOrCopy(source, target); err != nil {
			return "", err
		}
		publicPath = filepath.Join(taskDest, name)
	} else {
		prefix := commonParent(files)
		for _, file := range files {
			rel := file
			if prefix != "" {
				rel = strings.TrimPrefix(rel, prefix+"/")
			}
			if rel == "" || rel == "." {
				rel = filepath.Base(file)
			}
			source := filepath.Join(sourceDir, filepath.FromSlash(file))
			target := filepath.Join(tmp, filepath.FromSlash(rel))
			if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
				return "", err
			}
			if err := linkOrCopy(source, target); err != nil {
				return "", err
			}
		}
	}

	old := taskDest + ".old"
	_ = os.RemoveAll(old)
	if _, err := os.Stat(taskDest); err == nil {
		if err := os.Rename(taskDest, old); err != nil {
			return "", err
		}
	}
	if err := os.Rename(tmp, taskDest); err != nil {
		if _, statErr := os.Stat(old); statErr == nil {
			_ = os.Rename(old, taskDest)
		}
		return "", err
	}
	_ = os.RemoveAll(old)
	return publicPath, nil
}

func ensurePublicRoot(root string) (string, error) {
	for _, name := range []string{publicResultsDir, publicResultsFallbackDir} {
		path := filepath.Join(root, name)
		info, err := os.Stat(path)
		switch {
		case os.IsNotExist(err):
			if err := os.Mkdir(path, 0o755); err != nil {
				return "", err
			}
			if err := os.WriteFile(filepath.Join(path, managedMarkerName), []byte(managedMarkerContents), 0o644); err != nil {
				_ = os.Remove(path)
				return "", err
			}
			return path, nil
		case err != nil:
			return "", err
		case !info.IsDir():
			continue
		case IsManagedPublicRoot(path):
			return path, nil
		default:
			// Never claim or modify a pre-existing user directory. Try the
			// namespaced fallback instead.
			continue
		}
	}
	return "", fmt.Errorf("cannot create Routurn result view: both %q and %q already exist and are not Routurn-managed", publicResultsDir, publicResultsFallbackDir)
}

func relativePublicPath(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil || strings.HasPrefix(rel, "..") {
		return path
	}
	return filepath.ToSlash(rel)
}

func stableSuffix(name string) string {
	lower := strings.ToLower(name)
	for _, suffix := range []string{".tar.gz", ".tar.bz2", ".tar.xz", ".tar.zst"} {
		if strings.HasSuffix(lower, suffix) {
			return name[len(name)-len(suffix):]
		}
	}
	return filepath.Ext(name)
}

func commonParent(files []string) string {
	if len(files) < 2 {
		return ""
	}
	parts := strings.Split(filepath.ToSlash(filepath.Dir(files[0])), "/")
	if len(parts) == 1 && parts[0] == "." {
		return ""
	}
	for _, file := range files[1:] {
		other := strings.Split(filepath.ToSlash(filepath.Dir(file)), "/")
		n := len(parts)
		if len(other) < n {
			n = len(other)
		}
		i := 0
		for i < n && parts[i] == other[i] {
			i++
		}
		parts = parts[:i]
		if len(parts) == 0 {
			return ""
		}
	}
	return strings.Join(parts, "/")
}

func linkOrCopy(source, target string) error {
	if err := os.Link(source, target); err == nil {
		return nil
	}
	info, err := os.Stat(source)
	if err != nil {
		return err
	}
	src, err := os.Open(source)
	if err != nil {
		return err
	}
	defer src.Close()
	dst, err := os.OpenFile(target, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, info.Mode().Perm())
	if err != nil {
		return err
	}
	_, cpErr := io.Copy(dst, src)
	closeErr := dst.Close()
	if cpErr != nil {
		return cpErr
	}
	return closeErr
}

func ensureGitLocalExclude(root, publicName string) error {
	gitPath := filepath.Join(root, ".git")
	info, err := os.Stat(gitPath)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	gitDir := gitPath
	if !info.IsDir() {
		data, err := os.ReadFile(gitPath)
		if err != nil {
			return err
		}
		line := strings.TrimSpace(string(data))
		if !strings.HasPrefix(line, "gitdir:") {
			return nil
		}
		gitDir = strings.TrimSpace(strings.TrimPrefix(line, "gitdir:"))
		if !filepath.IsAbs(gitDir) {
			gitDir = filepath.Join(root, gitDir)
		}
	}
	infoDir := filepath.Join(gitDir, "info")
	if err := os.MkdirAll(infoDir, 0o755); err != nil {
		return err
	}
	excludePath := filepath.Join(infoDir, "exclude")
	data, err := os.ReadFile(excludePath)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	pattern := "/" + publicName + "/"
	for _, line := range strings.Split(string(data), "\n") {
		if strings.TrimSpace(line) == pattern {
			return nil
		}
	}
	f, err := os.OpenFile(excludePath, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	if len(data) > 0 && data[len(data)-1] != '\n' {
		if _, err := f.WriteString("\n"); err != nil {
			return err
		}
	}
	_, err = f.WriteString("# Routurn generated result view\n" + pattern + "\n")
	return err
}

func copyTree(source, dest string) ([]string, error) {
	sourceAbs, err := filepath.Abs(source)
	if err != nil {
		return nil, err
	}
	var files []string
	err = filepath.WalkDir(sourceAbs, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, err := filepath.Rel(sourceAbs, path)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("result contains symlink: %s", filepath.ToSlash(rel))
		}
		target := filepath.Join(dest, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return fmt.Errorf("result contains unsupported file type: %s", filepath.ToSlash(rel))
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		src, err := os.Open(path)
		if err != nil {
			return err
		}
		dst, err := os.OpenFile(target, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, info.Mode().Perm())
		if err != nil {
			src.Close()
			return err
		}
		_, cpErr := io.Copy(dst, src)
		closeSrcErr := src.Close()
		closeDstErr := dst.Close()
		if cpErr != nil {
			return cpErr
		}
		if closeSrcErr != nil {
			return closeSrcErr
		}
		if closeDstErr != nil {
			return closeDstErr
		}
		files = append(files, filepath.ToSlash(rel))
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	return files, nil
}

func writeMetadata(path string, meta Metadata) error {
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return os.WriteFile(path, data, 0o644)
}

func taskDirName(task string) string {
	var b strings.Builder
	changed := false
	for _, r := range task {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '-' || r == '_' || r == '.' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
			changed = true
		}
	}
	name := strings.Trim(b.String(), ".")
	if name == "" {
		name = "task"
		changed = true
	}
	if !changed {
		return name
	}
	h := sha256.Sum256([]byte(task))
	return name + "-" + hex.EncodeToString(h[:4])
}
